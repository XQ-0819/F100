/*
* brief : package modbus message
* param : addr[in]:dev addr
*         func[in]:control
*         reg[in]:reg
*         regn[in]:reg number
*         buf[in]:buffer
*         size[in]:buffer size
* result: -1:param error
*         >0:message length
*/
int MODBUS_PackMsg( BYTE addr, BYTE func, BYTE* reg, BYTE regn, BYTE* buf, int size )
{
    int		it;
    WORD	wCrc;
    PSL_PDU_RD	pPduR;

    if ( reg == NULL || buf == NULL ||
            size < sizeof(TSL_PDU_RD) ) {
        return -1;
    }

    pPduR = (PSL_PDU_RD)buf;
    pPduR->addr = addr;
    pPduR->pdu.func = func;
    pPduR->pdu.addr.x[0] = reg[1]; // msb
    pPduR->pdu.addr.x[1] = reg[0]; // lsb
    pPduR->pdu.num.x[0] = 0;
    pPduR->pdu.num.x[1] = regn;

    it = 1 + sizeof(TPDU_RD);
    wCrc = GetCRCDict( buf, it );
    buf[it++] = wCrc & 0xff;
    buf[it++] = (wCrc >> 8) & 0xff;

    return it;
}

int MODBUS_WriteMsg( BYTE addr, BYTE func, BYTE* reg, BYTE* data, BYTE* buf, int size )
{
    int		it;
    WORD	wCrc;
    PSL_PDU_WD	pPduW;

    if ( reg == NULL || buf == NULL || data == NULL ||
            size < sizeof(TSL_PDU_WD) ) {
        return -1;
    }

    pPduW = (PSL_PDU_WD)buf;
    pPduW->addr = addr;
    pPduW->pdu.func = func;
    pPduW->pdu.addr.x[0] = reg[1]; // msb
    pPduW->pdu.addr.x[1] = reg[0]; // lsb
    pPduW->pdu.value.x[0] = data[1]; // msb
    pPduW->pdu.value.x[1] = data[0]; // lsb

    it = 1 + sizeof(TPDU_WD);
    wCrc = GetCRCDict( buf, it );
    buf[it++] = wCrc & 0xff;
    buf[it++] = (wCrc >> 8) & 0xff;

    return it;
}


/*
* brief : get modbus data segment
* param : addr[in]:device address
*         func[in]:fun code
*         buf[in/out]:message buffer
*         msgLn[in]:message length
* result: <0:error
*         =0:ctrl error
*         >0:data length
*/
int MODBUS_GetDatSeg( BYTE addr, BYTE func, BYTE* buf, int msgLn )
{
    int		it, bytes;
    WORD	wCRC1, wCRC2;
    BYTE*	pItData;
    PSL_PDUA_HEAD	pHeadA;

    if ( buf == NULL || msgLn < sizeof(TSL_PDUA_HEAD) ) {
        return -1;
    }

    for ( it = 0; it < msgLn; it++ ) {
        if ( buf[it] == addr ) {
            break;
        }
    }

    if ( (msgLn - it) < sizeof(TSL_PDUA_HEAD) ) {
        return -2;
    }

    pHeadA = (PSL_PDUA_HEAD)&buf[it];

    // check address and control code
    if ( pHeadA->addr != addr 
		/*||pHeadA->pdu.func != func*/ ) {
        return -3;
    }

    // check crc code
    wCRC1 = GetCRCDict( &pHeadA->addr, msgLn - it - 2 );
    wCRC2 = (buf[msgLn - it - 1] << 8) | buf[msgLn - it - 2];

    if ( wCRC1 != wCRC2 ) {
        return -4;
    }

    // pick data
    bytes = pHeadA->pdu.bytes;
    pItData = &pHeadA->pdu.data;
    memcpy( buf, pItData, bytes );

    return bytes;
}

int MODBUS_GetWrAck( BYTE addr, BYTE func, BYTE* reg, BYTE* data, BYTE* buf, int msgLn )
{
    int		it;
    WORD	wCRC1, wCRC2;
    PSL_PDUA_WHEAD	pHeadA;

    if ( buf == NULL || msgLn < sizeof(TSL_PDUA_WHEAD) ) {
        return -1;
    }

    for ( it = 0; it < msgLn; it++ ) {
        if ( buf[it] == addr ) {
            break;
        }
    }

    if ( (msgLn - it) < sizeof(TSL_PDUA_WHEAD) ) {
        return -2;
    }

    pHeadA = (PSL_PDUA_WHEAD)&buf[it];

    // check address and control code
    if ( pHeadA->addr != addr ||
            pHeadA->pdu.func != func ) {
        return -3;
    }

    // check crc code
    wCRC1 = GetCRCDict( &pHeadA->addr, msgLn - it - 2 );
    wCRC2 = (buf[msgLn - it - 1] << 8) | buf[msgLn - it - 2];

    if ( wCRC1 != wCRC2 ) {
        return -4;
    }

    // check code
    if (	pHeadA->pdu.addr.x[0] != reg[1] || // msb
            pHeadA->pdu.addr.x[1] != reg[0] || // lsb
            pHeadA->pdu.value.x[0] != data[1] || // msb
            pHeadA->pdu.value.x[1] != data[0]) { // lsb
        return -5;
    }

    return 1;
}


