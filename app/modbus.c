WORD GetCRCDict( BYTE *msg, int ln )
{
    int		index;
    BYTE bCRCHi = 0xFF; // CRC 的高字节初始化
    BYTE bCRCLo = 0xFF; // CRC 的低字节初始化

    if ( msg == NULL || ln < 1 ) {
        return 0xFFFF;
    }

    while ( ln--) {
        index = bCRCLo ^ *msg++;
        bCRCLo = bCRCHi ^ CRCHi[index];
        bCRCHi = CRCLo[index];
    }

    return (bCRCHi << 8 | bCRCLo);
}

WORD GetCRC16( BYTE *msg, int ln, WORD crc )
{
    int		index;
    BYTE bCRCHi = (BYTE)(crc >> 8); // CRC 的高字节初始化
    BYTE bCRCLo = (BYTE)crc; // CRC 的低字节初始化

    if ( msg == NULL || ln < 1 ) {
        return 0xFFFF;
    }

    while ( ln--) {
        index = bCRCLo ^ *msg++;
        bCRCLo = bCRCHi ^ CRCHi[index];
        bCRCHi = CRCLo[index];
    }

    return (bCRCHi << 8 | bCRCLo);
}



