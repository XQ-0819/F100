#define INIT_CRC	(0xFFFF)
#define CRC_POLY	(0xA001)

/*
* brief   : get crc code
* param   : msg[in]:message buffer
*           ln[in]:message length
* result  : crc code
*/
WORD GetCRC( BYTE* msg, int ln )
{
    int		i, j;
    WORD	wCrc = INIT_CRC;

    if ( msg == NULL || ln < 1 ) {
        return wCrc;
    }

    for ( i = 0; i < ln; i++ ) {
        wCrc ^= msg[i];

        for ( j = 0; j < 8; j++ ) {
            wCrc >>= 1;

            if ( wCrc & 0x01 ) {
                wCrc ^= CRC_POLY;
            }
        }
    }

    return wCrc;
}

/*
* brief   : get lrc code
* param   : msg[in]:message buffer
*           ln[in]:message length
* result  : lrc code
*/
int GetLRC( BYTE* msg, int ln )
{
    int		i;
    BYTE	bLrc = 0;

    if ( msg == NULL || ln < 1 ) {
        return -1;
    }

    for ( i = 0; i < ln; i++ ) {
        bLrc += msg[i];
    }

    return ~bLrc;
}

